/**
 * Per-hostname configuration accepted by the middleware's `multidomainConfig`.
 * Mirrors DomainMiddlewareOptionsSchema in @appwarden/middleware.
 */
export interface HostnameConfig {
  debug?: boolean
  bypassPaths?: string[]
  website?: {
    lockPageSlug?: string
    cspMode?: "disabled" | "report-only" | "enforced"
    cspDirectives?: Record<string, unknown>
  }
  api?: {
    basePaths?: string[]
    response?: {
      status?: number
      body?: string
      headers?: { name: string; value: string }[]
    }
  }
}

export type GeneratedConfig = Record<string, HostnameConfig>

/**
 * Per-hostname middleware options returned from the API.
 *
 * The API returns the domain-configuration file format: kebab-case keys, with
 * the website and API settings nested under `website` and `api`.
 */
export type HostnameMiddlewareOptions = {
  debug?: string | boolean
  "bypass-paths"?: string[]
  website?: {
    "lock-page-slug"?: string
    "csp-mode"?: "disabled" | "report-only" | "enforced"
    "csp-directives"?: Record<string, unknown>
  }
  api?: {
    "base-paths"?: string[]
    response?: {
      status?: number
      body?: string
      headers?: { name: string; value: string }[]
    }
  }
}

export interface HydratedGeneratedConfig {
  configString: string
  config: GeneratedConfig
  hostnames: string[]
  debug: boolean
}

/**
 * Extracts hostnames from the generated config.
 * Hostnames are the top-level keys in the config object.
 */
export const extractHostnamesFromConfig = (
  config: GeneratedConfig,
): string[] => {
  return Object.keys(config)
}

export const hydrateGeneratedConfig = (
  middlewareOptionsMap: Map<string, HostnameMiddlewareOptions>,
): HydratedGeneratedConfig => {
  const config: GeneratedConfig = {}

  // Extract debug value - if ANY hostname has debug enabled, enable it globally
  let debug = false
  for (const [, options] of middlewareOptionsMap) {
    if (options?.debug) {
      // Handle both string "true"/"false" and boolean values
      const debugValue =
        typeof options.debug === "string"
          ? options.debug.toLowerCase() === "true"
          : options.debug
      if (debugValue) {
        debug = true
        break // Once we find one enabled, we can stop
      }
    }
  }

  // Build config with all properties nested under each hostname
  for (const [hostname, options] of middlewareOptionsMap) {
    const hostnameConfig: HostnameConfig = {}

    // Add debug if present
    if (options?.debug !== undefined) {
      // Handle both string "true"/"false" and boolean values
      const debugValue =
        typeof options.debug === "string"
          ? options.debug.toLowerCase() === "true"
          : options.debug
      hostnameConfig.debug = debugValue
    }

    // Add bypassPaths if present
    if (options?.["bypass-paths"]?.length) {
      hostnameConfig.bypassPaths = options["bypass-paths"]
    }

    // Add website settings (lock page and CSP) if present
    const website = options?.website
    if (website) {
      const websiteConfig: NonNullable<HostnameConfig["website"]> = {}
      if (website["lock-page-slug"]) {
        websiteConfig.lockPageSlug = website["lock-page-slug"]
      }
      if (website["csp-mode"]) {
        websiteConfig.cspMode = website["csp-mode"]
      }
      if (website["csp-directives"]) {
        websiteConfig.cspDirectives = website["csp-directives"]
      }
      if (Object.keys(websiteConfig).length > 0) {
        hostnameConfig.website = websiteConfig
      }
    }

    // Add API settings if present
    const api = options?.api
    if (api) {
      const apiConfig: NonNullable<HostnameConfig["api"]> = {}
      if (api["base-paths"]?.length) {
        apiConfig.basePaths = api["base-paths"]
      }
      if (api.response) {
        apiConfig.response = api.response
      }
      if (Object.keys(apiConfig).length > 0) {
        hostnameConfig.api = apiConfig
      }
    }

    // Only add hostname to config if it has at least one property
    if (Object.keys(hostnameConfig).length > 0) {
      config[hostname] = hostnameConfig
    }
  }

  const hostnames = extractHostnamesFromConfig(config)

  const configString = `// This file is auto-generated by @appwarden/build-cloudflare-action
// Do not edit manually

export const config = ${JSON.stringify(config, null, 2)}
`

  return { configString, config, hostnames, debug }
}

export const generatedConfigTemplate = `// This file is auto-generated by @appwarden/build-cloudflare-action
// Do not edit manually

export const config = {}
`
